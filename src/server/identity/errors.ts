export type AuthenticationErrorName = keyof typeof AUTHENTICATION_ERROR_CODES

/**
 * Plane `AuthenticationException`: error_code + error_message (+ payload) as the response body.
 * Thrown as a ServiceError so Hono's onError and Better Auth hooks share one shape.
 */
export function authenticationError(
  name: AuthenticationErrorName,
  status = 400,
  payload: Record<string, unknown> = {}
): ServiceError {
  return new ServiceError(status, name, name, { error_code: AUTHENTICATION_ERROR_CODES[name], error_message: name, ...payload })
}

/** Plane `get_error_dict`. */
export function getErrorDict(name: AuthenticationErrorName, payload: Record<string, unknown> = {}) {
  return { error_code: AUTHENTICATION_ERROR_CODES[name], error_message: name, ...payload }
}

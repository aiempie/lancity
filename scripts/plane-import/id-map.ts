import type { IdMapSnapshot } from '../../src/types/database/p4-migrations-schema'

const normalize = (key: unknown) => String(key).trim().toLowerCase()

/** UUID to auto-increment ID mapping, one counter per D1 table. IDs are stable once allocated. */
export class IdMap {
  #ids = new Map<string, Map<string, number>>()
  #next = new Map<string, number>()

  constructor(snapshot?: IdMapSnapshot) {
    for (const [table, entry] of Object.entries(snapshot?.tables ?? {})) {
      this.#ids.set(table, new Map(Object.entries(entry.ids)))
      this.#next.set(table, entry.next)
    }
  }

  /** Reserve IDs above the highest one already used in a non-empty D1 table. */
  setStart(table: string, firstId: number) {
    this.#next.set(table, Math.max(this.#next.get(table) ?? 1, firstId))
  }

  /** The ID of a source key, allocating the next one on first use. */
  allocate(table: string, key: unknown): number {
    const map = this.#table(table)
    const name = normalize(key)
    const existing = map.get(name)
    if (existing !== undefined) return existing
    return this.#store(table, map, name)
  }

  /** A fresh ID for a row that has no source key (generated by a migration rule). */
  create(table: string): number {
    return this.#store(table, this.#table(table), `generated:${this.#next.get(table) ?? 1}`)
  }

  get(table: string, key: unknown): number | undefined {
    return this.#ids.get(table)?.get(normalize(key))
  }

  has(table: string, key: unknown): boolean {
    return this.get(table, key) !== undefined
  }

  snapshot(): IdMapSnapshot {
    const tables: IdMapSnapshot['tables'] = {}
    for (const [table, ids] of this.#ids) tables[table] = { next: this.#next.get(table) ?? 1, ids: Object.fromEntries(ids) }
    return { tables }
  }

  #table(table: string) {
    let map = this.#ids.get(table)
    if (!map) this.#ids.set(table, (map = new Map()))
    return map
  }

  #store(table: string, map: Map<string, number>, name: string) {
    const id = this.#next.get(table) ?? 1
    this.#next.set(table, id + 1)
    map.set(name, id)
    return id
  }
}
